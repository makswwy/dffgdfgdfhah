def _normalize_text(value: Any) -> str:
    text = str(value or "").lower().replace("ё", "е")
    text = re.sub(r"https?://", " ", text)
    text = re.sub(r"[\[\]{}()|/@#*_+=:;,.!?\"'«»<>-]+", " ", text)
    return re.sub(r"\s+", " ", text).strip()


def _contains_any(text: str, terms: set[str]) -> bool:
    padded = f" {text} "
    return any((term in text if " " in term else f" {term} " in padded) for term in terms)


def build_ad_safety_text(data: dict[str, Any] | None) -> str:
    if not isinstance(data, dict):
        return ""
    parts = [
        data.get("text"),
        data.get("button_title"),
        data.get("button_link"),
        data.get("custom_button_title"),
        data.get("custom_button_link"),
        data.get("url"),
        data.get("link"),
        data.get("rate_name"),
    ]
    attachment = data.get("attachment")
    if isinstance(attachment, dict):
        parts.extend([attachment.get("title"), attachment.get("url")])
    return "\n".join(str(part) for part in parts if part)


def detect_military_recruitment(text: str | dict[str, Any] | None) -> dict[str, Any]:
    raw_text = build_ad_safety_text(text) if isinstance(text, dict) else str(text or "")
    normalized = _normalize_text(raw_text)
    if not normalized:
        return {"blocked": False, "reason": ""}

    for pattern in _DIRECT_PATTERNS:
        if re.search(pattern, normalized):
            return {
                "blocked": True,
                "reason": (
                    "Материал содержит признаки рекламы набора/оформления на военную службу, участия в боевых действиях "
                    "или работы с БПЛА/FPV/дронами в военном контексте."
                ),
                "policy": MILITARY_RECRUITMENT_POLICY_NAME,
                "legal_basis": MILITARY_RECRUITMENT_LEGAL_BASIS,
            }

    if _contains_any(normalized, _RECRUITMENT_TERMS) and _contains_any(normalized, _MILITARY_TERMS):
        return {
            "blocked": True,
            "reason": (
                "В тексте одновременно найдены признаки набора/трудоустройства/контракта и военной тематики "
                "(ВС РФ, СВО, бой, войска, БПЛА/FPV/дроны и т.п.)."
            ),
            "policy": MILITARY_RECRUITMENT_POLICY_NAME,
            "legal_basis": MILITARY_RECRUITMENT_LEGAL_BASIS,
        }

    return {"blocked": False, "reason": ""}


